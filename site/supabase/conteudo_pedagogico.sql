-- Conteúdo pedagógico permanente do Robô Literário.
-- O script é idempotente: pode ser executado novamente.
-- Não apaga nem recria atividades, frases, equipes, leituras, pontuações ou trechos_embaralhar.

CREATE TABLE IF NOT EXISTS public.contos (
  id text NOT NULL,
  titulo text NOT NULL,
  autor text,
  resumo text,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT contos_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS public.perguntas (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  conto_id text NOT NULL,
  ordem integer NOT NULL,
  pergunta text NOT NULL,
  resposta text NOT NULL,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT perguntas_pkey PRIMARY KEY (id),
  CONSTRAINT perguntas_conto_id_fkey
    FOREIGN KEY (conto_id) REFERENCES public.contos(id) ON DELETE CASCADE,
  CONSTRAINT perguntas_conto_ordem_key UNIQUE (conto_id, ordem)
);

CREATE TABLE IF NOT EXISTS public.desafios (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  conto_id text NOT NULL,
  ordem integer NOT NULL,
  momento text,
  texto text NOT NULL,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT desafios_pkey PRIMARY KEY (id),
  CONSTRAINT desafios_conto_id_fkey
    FOREIGN KEY (conto_id) REFERENCES public.contos(id) ON DELETE CASCADE,
  CONSTRAINT desafios_conto_ordem_key UNIQUE (conto_id, ordem)
);

CREATE TABLE IF NOT EXISTS public.dicas (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  conto_id text NOT NULL,
  trecho_id integer,
  ordem integer NOT NULL,
  texto text NOT NULL,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT dicas_pkey PRIMARY KEY (id),
  CONSTRAINT dicas_conto_id_fkey
    FOREIGN KEY (conto_id) REFERENCES public.contos(id) ON DELETE CASCADE,
  CONSTRAINT dicas_conto_ordem_key UNIQUE (conto_id, ordem)
);

-- Compatibilidade com bancos onde as tabelas acima já foram criadas pela versão anterior.
ALTER TABLE public.desafios
  ADD COLUMN IF NOT EXISTS momento text;

ALTER TABLE public.dicas
  ADD COLUMN IF NOT EXISTS trecho_id integer;

-- A dica pode ser geral (trecho_id NULL) ou, futuramente, ligada a um trecho específico.
-- Nenhum vínculo é criado automaticamente porque o material recebido não define essa correspondência.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'dicas_trecho_id_fkey'
  ) THEN
    ALTER TABLE public.dicas
      ADD CONSTRAINT dicas_trecho_id_fkey
      FOREIGN KEY (trecho_id)
      REFERENCES public.trechos_embaralhar(id)
      ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS dicas_trecho_id_idx
  ON public.dicas(trecho_id);
