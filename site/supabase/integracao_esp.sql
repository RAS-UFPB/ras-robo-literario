-- Integração direta ESP32 -> Supabase para o Robô Literário.
-- A ESP envia uma sessão inteira no formato:
-- {
--   "sessao_id": "AULA01",
--   "rodadas": [
--     { "equipe": 1, "sequencia": ["0000", "0010", "0001"] }
--   ]
-- }
--
-- Esta tabela é uma caixa de entrada bruta. Ela NÃO substitui as tabelas
-- atividades/frases/equipes/leituras, porque o firmware não conhece os IDs
-- relacionais usados nessas tabelas.

CREATE TABLE IF NOT EXISTS public.sessoes_esp (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sessao_id text NOT NULL,
  rodadas jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT sessoes_esp_sessao_id_check
    CHECK (char_length(trim(sessao_id)) BETWEEN 1 AND 31),
  CONSTRAINT sessoes_esp_rodadas_array_check
    CHECK (jsonb_typeof(rodadas) = 'array')
);

CREATE INDEX IF NOT EXISTS sessoes_esp_created_at_idx
  ON public.sessoes_esp(created_at DESC);

-- A chave anon fica na ESP, então ela deve ter SOMENTE permissão de INSERT
-- nesta tabela. O backend do site lê pelo PostgreSQL/Prisma usando DATABASE_URL.
ALTER TABLE public.sessoes_esp ENABLE ROW LEVEL SECURITY;

GRANT INSERT ON public.sessoes_esp TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.sessoes_esp_id_seq TO anon;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM pg_policies
     WHERE schemaname = 'public'
       AND tablename = 'sessoes_esp'
       AND policyname = 'esp_insere_sessoes'
  ) THEN
    CREATE POLICY esp_insere_sessoes
      ON public.sessoes_esp
      FOR INSERT
      TO anon
      WITH CHECK (
        char_length(trim(sessao_id)) BETWEEN 1 AND 31
        AND jsonb_typeof(rodadas) = 'array'
      );
  END IF;
END $$;
